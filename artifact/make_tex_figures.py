#!/usr/bin/env python3
r"""
Generate the paper's data-driven figures as native TikZ/pgfplots source.

    python artifact/make_tex_figures.py     # writes figures/fig_*.tex

Each output is a bare tikzpicture that the section files \input inside their own
figure environment, so captions/labels stay with the prose. Vector output, paper
fonts, diffable source -- and the frozen data files remain the single source of
truth, so a data change plus a rerun is the whole update path.

fig_instrument_structure.tex is hand-maintained (a schematic, not a plot) and is
not written by this script.
"""
import json, os
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, "artifact")
FIG = os.path.join(A, "figures")

BANNER = ("%% GENERATED by artifact/make_tex_figures.py from frozen data -- do not edit by hand.\n"
          "%% Source: {src}\n")

CATEGORY_LABEL = {
    "code-gen": "Code generation",
    "text2sql": "Text-to-SQL / DB",
    "tabular": "Tabular / spreadsheet",
    "ml-eng": "ML engineering",
    "e2e-agent": "End-to-end agents",
}

BLOCKER_LABEL = {
    "credential-or-service-blocked": "Credentials / services",
    "dependency-or-environment-failure": "Dependencies / environment",
    "missing-required-data": "Missing required data",
    "not-applicable": "Not applicable",
    "Grading rules & tie-breaking": "Grading \\& tie-breaking",
    "Predictions->aggregate-score mapping": "Predictions$\\rightarrow$score map",
    "Evaluator implementation available": "Evaluator implementation",
    "Metric definition": "Metric definition",
    "Input/expected-output schema": "I/O schema",
}

LABELS = ["not-documented", "access-blocked", "claimed-but-not-verifiable",
          "partially-documented", "documented-and-verifiable", "not-applicable"]
LABEL_COLOR = {
    "not-documented": "auditRed", "access-blocked": "auditPurple",
    "claimed-but-not-verifiable": "auditOrange", "partially-documented": "auditAmber",
    "documented-and-verifiable": "auditGreen", "not-applicable": "auditGrey",
}
LABEL_SHORT = {
    "not-documented": "Missing", "access-blocked": "Blocked",
    "claimed-but-not-verifiable": "Claimed", "partially-documented": "Partial",
    "documented-and-verifiable": "Verifiable", "not-applicable": "N/A",
}
R2_CRITERIA = ["Input/expected-output schema", "Metric definition",
               "Evaluator implementation available", "Grading rules & tie-breaking",
               "Predictions->aggregate-score mapping"]
PANEL_CRITERIA = R2_CRITERIA + ["Sample predictions / trajectories"]
CRIT_SHORT = ["I/O schema", "Metric", "Evaluator", "Grading", "Pred.$\\rightarrow$score", "Samples"]


def write(name, body, src):
    path = os.path.join(FIG, name)
    with open(path, "w") as handle:
        handle.write(BANNER.format(src=src) + body)
    print(f"[tex-fig] {os.path.relpath(path, ROOT)}")


def yticks(labels):
    """Index-based y ticks. Symbolic coords choke on '&', '/', commas; this does not."""
    return (f"  ytick={{{','.join(str(i) for i in range(len(labels)))}}},\n"
            f"  yticklabels={{{','.join('{' + l + '}' for l in labels)}}},\n"
            f"  ymin=-0.7, ymax={len(labels) - 0.3},")


def series(values, color, notes=None):
    pts = " ".join(f"({v},{i})" + (f" [{notes[i]}]" if notes else "")
                   for i, v in enumerate(values))
    return f"\\addplot[fill={color}, draw=none] coordinates {{{pts}}};"


def hbar_chart(rows, xlabel, color, height, xmax):
    """rows: list of (label, value). Simple labelled horizontal bar chart."""
    labels = [l for l, _ in rows]
    values = [v for _, v in rows]
    body = [
        r"\begin{tikzpicture}",
        r"\begin{axis}[auditbar,",
        f"  height={height},",
        f"  xlabel={{{xlabel}}},",
        f"  xmin=0, xmax={xmax},",
        yticks(labels),
        r"  nodes near coords, point meta=explicit symbolic,",
        r"]",
        series(values, color, [str(v) for v in values]),
        r"\end{axis}",
        r"\end{tikzpicture}",
    ]
    return "\n".join(body) + "\n"


def fig_corpus_composition(df):
    counts = df.category.value_counts()
    rows = [(CATEGORY_LABEL[c], int(counts[c])) for c in
            sorted(counts.index, key=lambda c: -counts[c])]
    body = hbar_chart(rows, "Benchmark releases", "auditBlue", "4.4cm", max(v for _, v in rows) + 2)
    write("fig_corpus_composition.tex", body, "analysis/master_outcomes.csv")


def fig_artifact_presence(stats):
    rq1 = stats["RQ1_accessibility"]
    order = [("Artifact: evaluator", "Evaluator code"),
             ("Artifact: dataset", "Dataset"),
             ("Artifact: license", "Explicit license"),
             ("Artifact: env_file", "Environment file"),
             ("Artifact: sample_predictions", "Sample predictions"),
             ("Artifact: container", "Container recipe")]
    labels, values, notes = [], [], []
    for key, label in order:
        k, n = rq1[key]["k"], rq1[key]["n"]
        labels.append(label)
        values.append(k)
        notes.append(f"{k}/{n}")
    body = [
        r"\begin{tikzpicture}",
        r"\begin{axis}[auditbar,",
        r"  height=4.8cm,",
        r"  xlabel={Releases with the artifact present (of 26)},",
        r"  xmin=0, xmax=31,",
        yticks(labels),
        r"  nodes near coords, point meta=explicit symbolic,",
        r"]",
        series(values, "auditGreen", notes),
        r"\end{axis}",
        r"\end{tikzpicture}",
    ]
    write("fig_artifact_presence.tex", "\n".join(body) + "\n", "analysis/phase6_stats.json")


def fig_e3_outcomes(df):
    order = ["tabular", "e2e-agent", "code-gen", "ml-eng", "text2sql"]
    rows = []
    for c in order:
        g = df[df.category == c]
        rows.append((CATEGORY_LABEL[c], int(g.E3_first_pass.sum()),
                     int(g.E3_after_repair.sum()), len(g)))
    labels = [r[0] for r in rows]
    body = [
        r"\begin{tikzpicture}",
        r"\begin{axis}[auditstack,",
        r"  height=4.6cm,",
        r"  xlabel={Releases in category},",
        r"  xmin=0, xmax=10.5, xtick={0,2,4,6,8},",
        yticks(labels),
        r"  legend style={at={(0.5,-0.32)}, anchor=north, legend columns=3},",
        r"]",
        series([r[1] for r in rows], "auditGreen"),
        r"\addlegendentry{pass as documented}",
        series([r[2] for r in rows], "auditAmber"),
        r"\addlegendentry{pass after repair}",
        series([r[3] - r[1] - r[2] for r in rows], "auditLight"),
        r"\addlegendentry{did not run}",
    ]
    # totals annotated at the end of each bar
    for i, (label, fp, rep, n) in enumerate(rows):
        body.append(f"\\node[font=\\tiny, anchor=west] at (axis cs:{n + 0.15},{i}) "
                    f"{{{fp}+{rep}/{n}}};")
    body += [r"\end{axis}", r"\end{tikzpicture}"]
    write("fig_e3_outcomes.tex", "\n".join(body) + "\n", "analysis/master_outcomes.csv")


def fig_failure_patterns(stats, ext):
    r2 = stats["RQ5_failure_patterns"]["R2_blocking_criteria"]
    # Corrected: all 21 first-pass failures, not the 19 that never scored.
    e3 = ext["blocker_taxonomy"]["first_pass_blockers"]
    r2_rows = sorted(((BLOCKER_LABEL.get(k, k), v) for k, v in r2.items()), key=lambda t: -t[1])
    e3_rows = sorted(((BLOCKER_LABEL.get(k, k), v) for k, v in e3.items()), key=lambda t: -t[1])

    def panel(rows, title, color, xmax):
        labels = [l for l, _ in rows]
        values = [v for _, v in rows]
        return "\n".join([
            r"\begin{axis}[auditbar,",
            r"  width=0.86\columnwidth, height=3.5cm,",
            f"  title={{\\scriptsize {title}}},",
            r"  title style={yshift=-1mm},",
            f"  xmin=0, xmax={xmax},",
            yticks(labels),
            r"  xtick={0,4,8,12},",
            r"  nodes near coords, point meta=explicit symbolic,",
            r"]",
            series(values, color, [str(v) for v in values]),
            r"\end{axis}",
        ])

    body = "\n".join([
        r"\begin{tikzpicture}",
        panel(r2_rows, r"R2 documentation blockers (of 26 releases)", "auditRed", 14),
        r"\begin{scope}[yshift=-3.9cm]",
        panel(e3_rows, r"First-pass execution blockers (of 21 failures)", "auditSlate", 11),
        r"\end{scope}",
        r"\end{tikzpicture}",
    ]) + "\n"
    write("fig_failure_patterns.tex", body,
          "analysis/phase6_stats.json + analysis/extended_analysis_stats.json")


def fig_r2_labels():
    panel = pd.read_csv(os.path.join(A, "audit", "model_panel_v1", "analysis",
                                     "aggregated_model_judgments.csv"))
    pivot = panel.pivot(index="benchmark", columns="criterion", values="aggregated_label")
    pivot = pivot.loc[sorted(pivot.index), PANEL_CRITERIA]
    benchmarks = list(pivot.index)
    cw, ch = 0.56, 0.30  # cell width/height in cm

    body = [r"\begin{tikzpicture}[x=1cm, y=1cm, font=\tiny]"]
    for row, bench in enumerate(benchmarks):
        y = -row * ch
        body.append(f"\\node[anchor=east, font=\\tiny] at ({-0.08},{y - ch/2:.3f}) "
                    f"{{{bench.replace('&', r'\&')}}};")
        for col, crit in enumerate(PANEL_CRITERIA):
            color = LABEL_COLOR[pivot.iloc[row][crit]]
            x = col * cw
            body.append(f"\\fill[{color}, draw=white, line width=0.4pt] "
                        f"({x:.3f},{y:.3f}) rectangle ({x + cw:.3f},{y - ch:.3f});")
    # criterion headers
    for col, short in enumerate(CRIT_SHORT):
        body.append(f"\\node[rotate=38, anchor=west, font=\\tiny] "
                    f"at ({col * cw + cw/2:.3f},0.08) {{{short}}};")
    # divider between the five R2 criteria and the sample-predictions input;
    # drawn in a gap so it reads as a separator rather than a cell border
    xdiv = 5 * cw
    body.append(f"\\draw[black, dashed, line width=1.1pt] ({xdiv:.3f},0.10) -- "
                f"({xdiv:.3f},{-len(benchmarks) * ch - 0.10:.3f});")
    # legend
    ylegend = -len(benchmarks) * ch - 0.55
    for i, label in enumerate(LABELS):
        x = (i % 3) * 1.30
        y = ylegend - (i // 3) * 0.32
        body.append(f"\\fill[{LABEL_COLOR[label]}] ({x:.3f},{y:.3f}) rectangle "
                    f"({x + 0.24:.3f},{y + 0.20:.3f});")
        body.append(f"\\node[anchor=west, font=\\tiny] at ({x + 0.30:.3f},{y + 0.10:.3f}) "
                    f"{{{LABEL_SHORT[label]}}};")
    body.append(r"\end{tikzpicture}")
    write("fig_r2_labels.tex", "\n".join(body) + "\n",
          "audit/model_panel_v1/analysis/aggregated_model_judgments.csv")


def main():
    df = pd.read_csv(os.path.join(A, "analysis", "master_outcomes.csv"))
    stats = json.load(open(os.path.join(A, "analysis", "phase6_stats.json")))
    ext_path = os.path.join(A, "analysis", "extended_analysis_stats.json")
    if not os.path.exists(ext_path):
        raise SystemExit("run artifact/analysis/build_extended_analysis.py first")
    ext = json.load(open(ext_path))

    fig_corpus_composition(df)
    fig_artifact_presence(stats)
    fig_e3_outcomes(df)
    fig_failure_patterns(stats, ext)
    fig_r2_labels()
    print("[tex-fig] done (fig_instrument_structure.tex is hand-maintained)")


if __name__ == "__main__":
    main()
